final List<String> _shuffled = List.of(practiceTips)..shuffle(Random(2026));

/// The three tips to show on [date].
List<String> tipsForDay(DateTime date) {
  final day = date.difference(DateTime(date.year, 1, 1)).inDays;
  final start = (day * 3) % _shuffled.length;
  return [for (var i = 0; i < 3; i++) _shuffled[(start + i) % _shuffled.length]];
}
